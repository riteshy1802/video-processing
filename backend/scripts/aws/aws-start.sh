#!/usr/bin/env bash
set -Eeuo pipefail

REGION="ap-southeast-2"
CLUSTER="video-processing"
IMAGE_TAG="${1:-latest}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
AWS_SCRIPTS="$ROOT/scripts/aws"
LIB="$AWS_SCRIPTS/lib"

cd "$ROOT"

echo "============================================================"
echo " START VIDEO PROCESSING AWS ENVIRONMENT"
echo "============================================================"
echo "Region:    $REGION"
echo "Cluster:   $CLUSTER"
echo "Image tag: $IMAGE_TAG"
echo "============================================================"

# ------------------------------------------------------------
# Required local tools
# ------------------------------------------------------------

echo
echo "[1/11] Checking local tools..."

for cmd in aws kubectl eksctl helm docker; do
    if ! command -v "$cmd" >/dev/null 2>&1; then
        echo "ERROR: '$cmd' is required."
        exit 1
    fi
done

aws sts get-caller-identity >/dev/null

# ------------------------------------------------------------
# Backend image
# ------------------------------------------------------------

echo
echo "[2/11] Building and uploading backend..."

"$AWS_SCRIPTS/aws-build-upload.sh" "$IMAGE_TAG"

# ------------------------------------------------------------
# EKS
# ------------------------------------------------------------

echo
echo "[3/11] Creating/checking EKS cluster..."

if aws eks describe-cluster \
    --name "$CLUSTER" \
    --region "$REGION" >/dev/null 2>&1; then

    echo "EKS cluster already exists."
else
    echo "Creating EKS cluster from eks-cluster.yaml..."

    eksctl create cluster -f "$ROOT/eks-cluster.yaml"
fi

aws eks update-kubeconfig \
    --name "$CLUSTER" \
    --region "$REGION" >/dev/null

echo
echo "Waiting for Kubernetes nodes..."

kubectl wait \
    --for=condition=Ready \
    nodes \
    --all \
    --timeout=900s

# ------------------------------------------------------------
# EBS CSI
# ------------------------------------------------------------

echo
echo "[4/11] Installing storage infrastructure..."

"$LIB/install-ebs-csi.sh"

# ------------------------------------------------------------
# Kafka
# ------------------------------------------------------------

echo
echo "[5/11] Installing Kafka..."

"$LIB/install-kafka.sh"

# ------------------------------------------------------------
# Redis + application
# ------------------------------------------------------------

echo
echo "[6/11] Deploying Redis and application workloads..."

kubectl apply -f "$ROOT/k8s/redis"

# Secret must already be generated by the deployment workflow.
echo
echo "Creating application secret..."

"$LIB/create-k8s-secret.sh"

kubectl apply -f "$ROOT/k8s/api"
kubectl apply -f "$ROOT/k8s/outbox"
kubectl apply -f "$ROOT/k8s/reconciler"
kubectl apply -f "$ROOT/k8s/planner"
kubectl apply -f "$ROOT/k8s/worker"
kubectl apply -f "$ROOT/k8s/finalizer"
kubectl apply -f "$ROOT/k8s/video-finalizer"

# ------------------------------------------------------------
# KEDA
# ------------------------------------------------------------

echo
echo "[7/11] Installing KEDA..."

"$LIB/install-keda.sh"

# ------------------------------------------------------------
# Cluster Autoscaler
# ------------------------------------------------------------

echo
echo "[8/11] Installing Cluster Autoscaler..."

"$LIB/install-cluster-autoscaler.sh"

# ------------------------------------------------------------
# AWS Load Balancer Controller
# ------------------------------------------------------------

echo
echo "[9/11] Installing AWS Load Balancer Controller..."

"$LIB/install-load-balancer-controller.sh"

# ------------------------------------------------------------
# API Ingress / ALB
# ------------------------------------------------------------

echo
echo "[10/11] Creating public API ALB..."

kubectl apply -f "$ROOT/k8s/api/ingress.yaml"

echo "Waiting for ALB hostname..."

ALB_HOST=""

for _ in {1..120}; do

    ALB_HOST=$(kubectl get ingress api \
        -n default \
        -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' \
        2>/dev/null || true)

    if [[ -n "$ALB_HOST" ]]; then
        break
    fi

    sleep 5
done

if [[ -z "$ALB_HOST" ]]; then
    echo "ERROR: ALB hostname was not created."
    kubectl describe ingress api -n default || true
    exit 1
fi

echo "ALB: $ALB_HOST"

# ------------------------------------------------------------
# CloudFront API origin
# ------------------------------------------------------------

echo
echo "[11/11] Updating API CloudFront origin..."

"$LIB/update-api-cloudfront.sh" "$ALB_HOST"

echo
echo "============================================================"
echo " AWS ENVIRONMENT STARTED"
echo "============================================================"

kubectl get nodes -L workload

echo
kubectl get pods -A

echo
kubectl get ingress api

echo
echo "Run:"
echo "  ./scripts/aws/check-running-instances.sh"
echo
echo "for the complete AWS resource audit."